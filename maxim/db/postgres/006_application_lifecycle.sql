CREATE TABLE evaluations(
 id uuid PRIMARY KEY,workspace_id uuid NOT NULL,job_id uuid NOT NULL,work_id uuid,
 revision integer NOT NULL DEFAULT 1,status text NOT NULL DEFAULT 'queued'
 CHECK(status IN ('queued','running','completed','review_required','failed','cancelled','stale')),
 job_revision integer NOT NULL,candidate_revision integer NOT NULL,input_snapshot jsonb NOT NULL,
 input_hash text NOT NULL,prompt_hash text NOT NULL,model text NOT NULL,provider text NOT NULL,
 score numeric CHECK(score BETWEEN 1 AND 5),tier text CHECK(tier IN ('T0','T1','T2','T3')),
 explanation text,archetype text,legitimacy text,liveness text NOT NULL DEFAULT 'unconfirmed',
 policy jsonb NOT NULL DEFAULT '{}',report_artifact_id uuid,output_manifest jsonb,
 error_code text,accounting jsonb,usage jsonb,created_at timestamptz NOT NULL DEFAULT now(),completed_at timestamptz,
 UNIQUE(workspace_id,id),FOREIGN KEY(workspace_id,job_id) REFERENCES jobs(workspace_id,id),
 FOREIGN KEY(workspace_id,work_id) REFERENCES work_items(workspace_id,id),
 FOREIGN KEY(workspace_id,report_artifact_id) REFERENCES artifacts(workspace_id,id)
);
CREATE TABLE application_packets(
 id uuid PRIMARY KEY,workspace_id uuid NOT NULL,application_id uuid NOT NULL,evaluation_id uuid NOT NULL,
 revision integer NOT NULL DEFAULT 1,status text NOT NULL DEFAULT 'draft'
 CHECK(status IN ('draft','approved','invalidated','revoked')),
 job_revision integer NOT NULL,candidate_revision integer NOT NULL,report_artifact_id uuid NOT NULL,pdf_artifact_id uuid NOT NULL,
 report_hash text NOT NULL,pdf_hash text NOT NULL,evidence jsonb NOT NULL,answers jsonb NOT NULL DEFAULT '[]',
 content_hash text NOT NULL,untailored boolean NOT NULL DEFAULT false,approval_reason text,
 approved_at timestamptz,created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(workspace_id,id),FOREIGN KEY(workspace_id,application_id) REFERENCES applications(workspace_id,id),
 FOREIGN KEY(workspace_id,evaluation_id) REFERENCES evaluations(workspace_id,id),
 FOREIGN KEY(workspace_id,report_artifact_id) REFERENCES artifacts(workspace_id,id),
 FOREIGN KEY(workspace_id,pdf_artifact_id) REFERENCES artifacts(workspace_id,id)
);
CREATE TABLE application_actions(
